#!/usr/bin/env node
/**
 * Generates the composer's font catalogue from the runtime's own font set.
 *
 * The faces themselves are loaded in `frontend/src/remotion-code/fonts.ts` —
 * that is the only place that can hold the `loadFont()` imports. But the
 * prompt that tells the model which faces exist is backend content, and
 * two hand-maintained lists drift the moment someone adds a font.
 *
 * So the frontend is the single source and this writes the prompt copy
 * out of it. Run after changing `FONTS`:
 *   node scripts/sync-font-catalogue.mjs
 */

import { readFileSync, writeFileSync } from "node:fs"
import { join, dirname } from "node:path"
import { fileURLToPath } from "node:url"

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = join(HERE, "..")
const SOURCE = join(ROOT, "..", "frontend", "src", "remotion-code", "fonts.ts")
const OUT = join(ROOT, "src", "lib", "font-catalogue.generated.ts")

const src = readFileSync(SOURCE, "utf8")

// Each entry reads: key: face(loadX, "role", "note"),
const rows = []
const re = /^\s*(\w+):\s*face\(load\w+,\s*"([a-z]+)",\s*"([^"]+)"\),/gm
for (const m of src.matchAll(re)) {
  rows.push({ key: m[1], role: m[2], note: m[3] })
}

if (rows.length === 0) {
  console.error("No fonts found in fonts.ts — refusing to write an empty catalogue.")
  process.exit(1)
}

// Prompt text, not data — so it is emitted as a list of ready-made lines
// and JSON-quoted, which keeps the em-dashes and punctuation from being
// parsed as TypeScript.
const body = rows
  .map(
    ({ key, role, note }) =>
      `  ${key}: "Fonts.${key}.family" — ${role} — ${note}`
  )
  .map((line) => `  ${JSON.stringify(line)},`)
  .join("\n")

writeFileSync(
  OUT,
  `// GENERATED by scripts/sync-font-catalogue.mjs — do not edit by hand.
//
// Source of truth: frontend/src/remotion-code/fonts.ts
// Those faces are preloaded at runtime, so a composition can reference
// them without an import and they still resolve inside the export worker,
// where a CDN @import would silently fail.
//
// Run \`node scripts/sync-font-catalogue.mjs\` after changing FONTS.

/** One prompt-ready line per preloaded face. */
export const FONT_CATALOGUE: readonly string[] = [
${body}
]

/** The whole catalogue, one face per line. */
export function fontCatalogue(): string {
  return FONT_CATALOGUE.join(String.fromCharCode(10))
}
`
)

console.log(`Wrote ${rows.length} fonts to src/lib/font-catalogue.generated.ts`)
