#!/usr/bin/env node
/**
 * Inlines skills/web-motion/*.md into backend/src/remotion/skills.generated.ts
 *
 * Why generated rather than read at runtime: the Worker has no filesystem, and
 * fetching from R2 or KV on every load_skill call would add latency and CPU to
 * a tool the model may call several times per turn. As a static import the
 * markdown is parsed once when the isolate starts and then costs nothing.
 *
 * Only ONE document is ever returned per call, so a single load_skill costs
 * roughly 1-3k tokens of context regardless of how many skills exist.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, "..", "..")
const srcDir = join(root, "skills", "web-motion")
const outFile = join(root, "backend", "src", "remotion", "skills.generated.ts")

/** Frontmatter description if the doc has one, else the first real line. */
function describe(name, body) {
  const fm = body.match(/^---\n([\s\S]*?)\n---/)
  if (fm) {
    const d = fm[1].match(/^description:\s*(.+)$/m)
    if (d) return d[1].trim()
  }
  const first = body
    .replace(/^---[\s\S]*?---\n/, "")
    .split("\n")
    .map((l) => l.trim())
    .find((l) => l && !l.startsWith("#"))
  return (first ?? name).slice(0, 160)
}

const files = readdirSync(srcDir)
  .filter((f) => f.endsWith(".md"))
  .sort()

const entries = files.map((f) => {
  const id = f.replace(/\.md$/, "")
  const body = readFileSync(join(srcDir, f), "utf8")
  return { id, description: describe(id, body), content: body }
})

// A working, hand-crafted bundle the model can imitate. Read straight out
// of the frontend source so the reference can never drift from what renders.
const demoPath = join(root, "frontend", "src", "web", "demo.ts")
let demoHtml = ""
let demoCss = ""
let demoJs = ""
try {
  const demoSrc = readFileSync(demoPath, "utf8")
  demoHtml = demoSrc.match(/const html = `([\s\S]*?)`\s*\n/)?.[1] ?? ""
  demoCss = demoSrc.match(/const css = `([\s\S]*?)`\s*\n/)?.[1] ?? ""
  demoJs = demoSrc.match(/const js = `([\s\S]*?)`\s*\n/)?.[1] ?? ""
} catch { /* demo optional — typography and the rest still build */ }
if (demoHtml && demoJs) {
  entries.push({
    id: "reference-cut",
    description:
      "A complete, working 150-frame product reveal bundle to imitate: anticipation, spring overshoot landing, masked headline, staggered finish.",
    content:
      "# Reference cut — imitate this, do not copy it\n\n" +
      "This bundle renders in the same sandboxed iframe your code will use. Study its structure:\n" +
      "- html: plain elements with ids (logo, headline, rule) inside #wm-stage\n" +
      "- css: scoped stylesheet, 'Space Grotesk' cited by family name\n" +
      "- js: render(t, ctx) with var f = ctx.frame; anticipation via ctx.interpolate, " +
      "spring landing via ctx.spring(t - start, { damping: 9 }), masked headline row, per-word stagger\n" +
      "- every move a pure function of t; no imports, no wall-clock\n\n" +
      "```html\n" + demoHtml + "\n```\n\n```css\n" + demoCss + "\n```\n\n```js\n" + demoJs + "\n```\n",
  })
}

const doc = `// GENERATED by backend/scripts/build-skills.mjs — do not edit by hand.
// Source: skills/web-motion/*.md   Regenerate: pnpm run skills:build

export interface Skill {
  /** The id passed to the load_skill tool. */
  id: string
  /** One line, shown in the catalogue so the model can pick without loading. */
  description: string
  /** The full document, returned only when load_skill is called. */
  content: string
}

export const SKILLS: Skill[] = ${JSON.stringify(entries, null, 2)}

const BY_ID = new Map(SKILLS.map((s) => [s.id, s]))

export function findSkill(id: string): Skill | undefined {
  return BY_ID.get(id.trim().toLowerCase())
}

/** Ids only — this is what goes in the system prompt, so it stays tiny. */
export const SKILL_IDS: string[] = SKILLS.map((s) => s.id)
`

mkdirSync(dirname(outFile), { recursive: true })
writeFileSync(outFile, doc)
console.log(
  `wrote ${outFile} — ${entries.length} skills, ${(doc.length / 1024).toFixed(0)}kB`
)
