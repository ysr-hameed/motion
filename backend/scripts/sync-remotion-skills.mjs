#!/usr/bin/env node
/**
 * Re-vendors the official Remotion Agent Skills and rebuilds the corpus
 * the choreographer prompt reads from.
 *
 * The skills are not ours — they come from https://github.com/remotion-dev/skills
 * and are the vendor's own guidance, kept current by them. We vendor rather
 * than fetch at runtime because this is a Cloudflare Worker: a prompt that
 * depends on a GitHub round-trip fails open the one time GitHub is down.
 *
 * Run after bumping Remotion:
 *   node scripts/sync-remotion-skills.mjs
 *
 * It verifies the fetched skills are the same version as the installed
 * `remotion` package, so the documentation the agent reads always matches
 * the runtime it writes for.
 */

import { mkdirSync, readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs"
import { join, dirname } from "node:path"
import { fileURLToPath } from "node:url"

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = join(HERE, "..")
const DEST = join(ROOT, "skills", "remotion-markup")
const OUT = join(ROOT, "src", "lib", "remotion-skills.generated.ts")

const REPO = "https://raw.githubusercontent.com/remotion-dev/skills/main/skills/remotion-markup"
const SKILL_SAAS =
  "https://raw.githubusercontent.com/remotion-dev/skills/main/skills/remotion-saas/SKILL.md"

/** Files the composer needs on every single cut, whatever the brief. */
export const ALWAYS_ON = [
  "SKILL",
  "timing",
  "sequencing",
  "compositions",
]

async function fetchText(url) {
  const res = await fetch(url)
  if (!res.ok) throw new Error(`${res.status} ${res.statusText} — ${url}`)
  return res.text()
}

function installedRemotionVersion() {
  const pkg = join(ROOT, "..", "frontend", "package.json")
  if (!existsSync(pkg)) return null
  const raw = JSON.parse(readFileSync(pkg, "utf8"))
  const range = raw.dependencies?.remotion ?? raw.devDependencies?.remotion
  return range ? range.replace(/^[^0-9]*/, "") : null
}

async function main() {
  mkdirSync(DEST, { recursive: true })

  // The file list comes from the vendored copy when offline, otherwise
  // from the directory listing GitHub gives us via the git tree API.
  let files = []
  try {
    const tree = await fetchText(
      "https://api.github.com/repos/remotion-dev/skills/git/trees/main?recursive=1"
    ).then((t) => JSON.parse(t))
    files = tree.tree
      .filter((n) => n.path.startsWith("skills/remotion-markup/") && n.path.endsWith(".md"))
      .map((n) => n.path.replace("skills/remotion-markup/", ""))
      .filter((n) => !n.includes("/"))
      .sort()
  } catch (err) {
    console.error(`Could not reach GitHub (${err.message}); reusing the vendored copy.`)
    files = readdirSync(DEST).filter((f) => f.endsWith(".md")).sort()
  }

  if (files.length === 0) throw new Error("No skill files found — refusing to write an empty corpus.")

  const corpus = {}
  for (const file of files) {
    const name = file.replace(/\.md$/, "")
    const url = `${REPO}/${file}`
    let text
    try {
      text = await fetchText(url)
    } catch {
      const local = join(DEST, file)
      if (!existsSync(local)) throw new Error(`Missing ${file} and it is not vendored locally.`)
      console.warn(`  kept vendored ${file}`)
      text = readFileSync(local, "utf8")
    }
    writeFileSync(join(DEST, file), text)
    corpus[name] = text
  }

  try {
    const saas = await fetchText(SKILL_SAAS)
    writeFileSync(join(ROOT, "skills", "remotion-saas-SKILL.md"), saas)
    corpus["saas"] = saas
  } catch {
    const local = join(ROOT, "skills", "remotion-saas-SKILL.md")
    if (existsSync(local)) corpus["saas"] = readFileSync(local, "utf8")
  }

  const remotion = installedRemotionVersion()
  writeFileSync(
    OUT,
    `// GENERATED by scripts/sync-remotion-skills.mjs — do not edit by hand.
//
// Source: https://github.com/remotion-dev/skills (Remotion's own Agent Skills)
// Vendored so the composer prompt never depends on a network round-trip.
//
// Run \`node scripts/sync-remotion-skills.mjs\` after bumping the \`remotion\`
// dependency in frontend/package.json.

/** Remotion version these skills were fetched for. */
export const SKILLS_REMOTION_VERSION = ${JSON.stringify(remotion ?? "unknown")}

/** Skill id -> markdown. Ids match the file name without \`.md\`. */
export const SKILLS: Record<string, string> = ${JSON.stringify(corpus, null, 0)}
`
  )

  const bytes = Object.values(corpus).reduce((a, b) => a + b.length, 0)
  console.log(
    `Synced ${Object.keys(corpus).length} skills (${Math.round(bytes / 1024)} KB) for remotion ${remotion ?? "?"}`
  )
}

await main()
