#!/usr/bin/env node
/**
 * Inlines the frontend's curated font catalogue into
 * backend/src/remotion/fonts.generated.ts
 *
 * The browser owns the runtime font loading (frontend/src/remotion-code/
 * fonts.ts), but the agent is the one who must know the registry exists.
 * The list is generated from the same source so a face added in one place
 * cannot drift out of sync with the other.
 *
 * Only the prompt-facing lines are emitted: key, role, note. Runtime code
 * (loaders, injection) stays in the browser.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, "..", "..")
const src = readFileSync(
  join(root, "frontend", "src", "remotion-code", "fonts.ts"),
  "utf8"
)
const outFile = join(root, "backend", "src", "remotion", "fonts.generated.ts")

const block = src.match(/const CATALOGUE:[^]*?\n\}\n/)
if (!block) throw new Error("Could not find CATALOGUE in fonts.ts")

const entries = [...block[0].matchAll(/^\s{2}(\w+): \{ role: "([^"]+)", note: "([^"]+)" \},/gm)]
if (entries.length === 0) throw new Error("No faces parsed from CATALOGUE")

const lines = entries.map(
  (m) => `- Fonts.${m[1]}.family — ${m[2]} — ${m[3]}`
)

const doc = `// GENERATED by backend/scripts/build-fonts.mjs — do not edit by hand.
// Source: frontend/src/remotion-code/fonts.ts   Regenerate: pnpm run fonts:build

/** Every set face, as prompt text. Keep byte-identical to fontCatalogue(). */
export const FONT_CATALOGUE = ${JSON.stringify(lines.join("\n"))}
`

mkdirSync(dirname(outFile), { recursive: true })
writeFileSync(outFile, doc)
console.log(`wrote ${outFile} — ${entries.length} faces`)
